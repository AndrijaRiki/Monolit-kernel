template <typename T>
inline T Riscv::r_user_reg(uint64 reg)
{
    T volatile ret;
    __asm__ volatile ("ld %[ret], %[reg]*8(fp)" : [ret] "=r"(ret) : [reg] "i"(reg));
    return ret;
}

template <typename T>
inline void Riscv::w_user_reg(uint64 reg, T val)
{
    __asm__ volatile ("sd %[val], %[reg]*8(fp)" : : [val] "r"(val), [reg] "i"(reg));
}

