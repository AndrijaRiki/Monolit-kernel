class Riscv
{
public:

    // pop sstatus.spp and sstatus.spie bits (has to be a non inline function)
    static void popSppSpie();

    // read register scause
    static uint64 r_scause();

    // write register scause
    static void w_scause(uint64 scause);

    // read register sepc
    static uint64 r_sepc();

    // write register sepc
    static void w_sepc(uint64 sepc);

    // read register stvec
    static uint64 r_stvec();

    // write register stvec
    static void w_stvec(uint64 stvec);

    // read register stval
    static uint64 r_stval();

    // write register stval
    static void w_stval(uint64 stval);

    enum BitMaskSip
    {
        SIP_SSIP = (1 << 1),
        SIP_STIP = (1 << 5),
        SIP_SEIP = (1 << 9),
    };

    // mask set register sip
    static void ms_sip(uint64 mask);

    // mask clear register sip
    static void mc_sip(uint64 mask);

    // read register sip
    static uint64 r_sip();

    // write register sip
    static void w_sip(uint64 sip);

    enum BitMaskSstatus
    {
        SSTATUS_SIE = (1 << 1),
        SSTATUS_SPIE = (1 << 5),
        SSTATUS_SPP = (1 << 8),
    };

    enum BitMaskSie
    {
        SIE_SSIE = (1 << 1),
        SIE_STIE = ( 1<< 5),
        SIE_SEIE = (1 << 9),
    };

    // mask set register sstatus
    static void ms_sstatus(uint64 mask);

    // mask clear register sstatus
    static void mc_sstatus(uint64 mask);

    // read register sstatus
    static uint64 r_sstatus();

    // write register sstatus
    static void w_sstatus(uint64 sstatus);

    // mask set register sie
    static void ms_sie(uint64 mask);

    // mask clear register sie
    static void mc_sie(uint64 mask);

    // read register sie
    static uint64 r_sie();

    // write register sie
    static void w_sie(uint64 sie);

    // read user register
    template <typename T>
    static T r_user_reg(uint64 reg);

    // write user register
    template <typename T>
    static void w_user_reg(uint64 reg, T val);

    // Installs our own trap vector (supervisorTrap, from trap.S) into stvec.
    // Must be called AFTER the platform's own boot/trapinithart() runs, since
    // that code unconditionally overwrites stvec with its own kernelvec right
    // before main() is entered. Called lazily/automatically from SysCalls::invoke
    // on first use, so user code never has to call this directly.
    static void initInternalTraps();
};

inline uint64 Riscv::r_scause()
{
    uint64 volatile scause;
    __asm__ volatile ("csrr %[scause], scause" : [scause] "=r"(scause));
    return scause;
}

inline void Riscv::w_scause(uint64 scause)
{
    __asm__ volatile ("csrw scause, %[scause]" : : [scause] "r"(scause));
}

